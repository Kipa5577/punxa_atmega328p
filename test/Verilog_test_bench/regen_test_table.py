import sys, os
WORK = '/home/claude/work/iter/work'
sys.path.insert(0, WORK)
os.chdir(os.path.join(WORK, 'isa_tests'))
sys.path.insert(0, '.')

import punxa_atmega328p as punxa
from punxa_atmega328p.assembly import assemble_program

order = [l.strip() for l in open('/tmp/full_test_order.txt') if l.strip()]
assert len(order) == 111, len(order)

all_words = []
entries = []  # (index, base, length, filename)

for idx, fname in enumerate(order):
    with open(os.path.join('isa', fname), 'r') as f:
        program = f.read()
    words, symbols = assemble_program(program)
    base = len(all_words)
    length = len(words)
    all_words.extend(words)
    entries.append((idx, base, length, fname))

# Index 111: ISP test reuses test_arith_ADD's image (index 1 in `order`)
add_entry = next(e for e in entries if e[3] == 'test_arith_ADD.asm')
isp_base, isp_len = add_entry[1], add_entry[2]

out_dir = '/home/claude/work/iter/regen_rom'
os.makedirs(out_dir, exist_ok=True)

with open(os.path.join(out_dir, 'prog_rom.hex'), 'w') as f:
    for w in all_words:
        f.write(f'{w:04x}\n')

with open(os.path.join(out_dir, 'test_table.vh'), 'w') as f:
    f.write("// Auto-generated by regen_test_table.py -- DO NOT hand-edit.\n")
    f.write("// One entry per test: base word-offset + length (in words) into prog_rom[],\n")
    f.write("// indexed into the flat instruction ROM assembled from the project's own\n")
    f.write("// isa_tests/isa/*.asm files (via punxa_atmega328p/assembly.py).\n")
    f.write("//\n")
    f.write("// Index 111 (the ISP test) is not a separate program: it reuses\n")
    f.write(f"// test_arith_ADD's image (base={isp_base} len={isp_len}) but is loaded through the real\n")
    f.write("// bit-serial ISP protocol (PROG_MOSI/PROG_SCK/PROG_MISO) instead of the\n")
    f.write("// direct preload used for indices 0..110.\n\n")
    f.write("localparam NUM_ISA_TESTS = 111;\n")
    f.write("localparam NUM_TESTS     = 112;  // 111 ISA + 1 full ISP flash-and-run test\n")
    f.write("localparam ISP_TEST_INDEX = 111;\n\n")
    f.write("reg [13:0] test_base [0:NUM_TESTS-1];\n")
    f.write("reg [8:0]  test_len  [0:NUM_TESTS-1];\n\n")
    f.write("initial begin\n")
    for idx, base, length, fname in entries:
        f.write(f"    test_base[{idx:3d}] = 14'd{base:<6}; test_len[{idx:3d}] = 9'd{length:<4}; // {fname}\n")
    f.write(f"    test_base[111] = 14'd{isp_base:<6}; test_len[111] = 9'd{isp_len:<4}; // ISP flash-and-run (reuses test_arith_ADD image)\n")
    f.write("end\n")

print("Total words:", len(all_words))
print("Wrote", out_dir)
